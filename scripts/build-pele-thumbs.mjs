import { promises as fs } from 'node:fs'
import path from 'node:path'
import { render } from 'pele'

const root = process.cwd()
const sourcePath = path.join(root, 'web', 'src', 'shared', 'pele', 'officialExamples.json')
const outputDir = path.join(root, 'public', 'pele-thumbs')
const manifestPath = path.join(
  root,
  'web',
  'src',
  'shared',
  'pele',
  'thumbnails.generated.ts',
)

const THEME_CSS = [
  '--pele-bg:#fffcf0',
  '--pele-fg:#100f0f',
  '--pele-fg-on-light:#1f1f1f',
  '--pele-fg-on-dark:#fff',
  '--pele-muted:#6f6e69',
  '--pele-line:#100f0f',
  '--pele-surface:#f2f0e5',
  '--pele-surface-alt:#e6e4d9',
  '--pele-border:#cecdc3',
  '--pele-accent:#205ea6',
  '--pele-critical:#af3029',
  '--pele-error:#af3029',
  '--pele-radius:6px',
  '--pele-font:-apple-system,BlinkMacSystemFont,Segoe UI,Helvetica,Arial,sans-serif',
  '--pele-font-mono:ui-monospace,SFMono-Regular,Menlo,Consolas,monospace',
  '--pele-series-1:#af3029',
  '--pele-series-2:#bc5215',
  '--pele-series-3:#ad8301',
  '--pele-series-4:#66800b',
  '--pele-series-5:#24837b',
  '--pele-series-6:#205ea6',
  '--pele-series-7:#5e409d',
  '--pele-series-8:#a02f6f',
].join(';')

function withTheme(svg) {
  return svg.replace(
    /<svg([^>]*)>/,
    `<svg$1><style>svg.pele{${THEME_CSS}}</style>`,
  )
}

function representative(group) {
  return group.examples[group.representativeIndex] ?? group.examples[0]
}

const groups = JSON.parse(await fs.readFile(sourcePath, 'utf8'))
await fs.rm(outputDir, { recursive: true, force: true })
await fs.mkdir(outputDir, { recursive: true })

const thumbnails = {}
const sizes = {}

for (const group of groups) {
  sizes[group.type] = []
  for (const example of group.examples) {
    try {
      const result = render(example.source)
      sizes[group.type].push({ width: result.width, height: result.height })
    } catch {
      sizes[group.type].push(null)
    }
  }

  const example = representative(group)
  if (!example) continue
  try {
    const result = render(example.source)
    const file = `${group.type}.svg`
    await fs.writeFile(path.join(outputDir, file), withTheme(result.svg), 'utf8')
    thumbnails[group.type] = {
      src: `pele-thumbs/${file}`,
      width: result.width,
      height: result.height,
    }
  } catch (error) {
    console.warn(`[pele-thumbs] ${group.type}: ${error.message}`)
  }
}

const source = `/* This file is generated by scripts/build-pele-thumbs.mjs. */
export interface PeleThumbnail {
  src: string
  width: number
  height: number
}

export interface PeleExampleSize {
  width: number
  height: number
}

export const PELE_THUMBNAILS: Record<string, PeleThumbnail> = ${JSON.stringify(
  thumbnails,
  null,
  2,
)}

export const PELE_EXAMPLE_SIZES: Record<
  string,
  Array<PeleExampleSize | null>
> = ${JSON.stringify(sizes, null, 2)}
`

await fs.writeFile(manifestPath, source, 'utf8')
console.log(
  `SuperBoard: 已生成 ${Object.keys(thumbnails).length} 个 Pele 一级缩略图，${Object.values(sizes).reduce((sum, items) => sum + items.length, 0)} 个示例尺寸`,
)
